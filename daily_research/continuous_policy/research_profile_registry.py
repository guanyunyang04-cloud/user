def get_search_profile_config(name: str) -> dict[str, Any]:
    profile_name = str(name)
    if profile_name not in ACTIVE_SEARCH_PROFILE_NAMES:
        raise KeyError(f"search profile is not active for new r58 studies: {profile_name}")
    return {
        "search_space": deepcopy(SEARCH_PROFILES[profile_name]),
        "base_trial": deepcopy(SEARCH_PROFILE_BASE_TRIALS[profile_name]),
        "default_objective": SEARCH_PROFILE_DEFAULT_OBJECTIVES.get(profile_name, "promotion_balanced_v2"),
        "resource_gate": deepcopy(RESOURCE_GATED_SEARCH_PROFILES.get(profile_name, {})),
        "true_solver_resource": profile_name in TRUE_SOLVER_RESOURCE_SEARCH_PROFILES,
    }


